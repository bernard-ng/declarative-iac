from __future__ import annotations

from declarative_iac.core.canonical import read_json
from declarative_iac.core.paths import results_dir
from declarative_iac.domain.report import tables


def test_tables_are_deterministic_and_cite_their_source():
    first = {name: build() for name, build in tables.TABLES.items()}
    second = {name: build() for name, build in tables.TABLES.items()}
    assert first == second
    for text in first.values():
        assert text.startswith("<!-- Generated by `declarative-iac report`")
        assert "Do not edit." in text.splitlines()[0]


def test_census_table_carries_the_result_values():
    summary = read_json(results_dir() / "static" / "S1-census" / "B1" / "summary.json")
    version = next(k for k in summary if k[0].isdigit())
    text = tables.census_roles()
    assert (
        f"| total | {summary[version]['operations']} | {summary[version]['used']['operations']} |"
        in text
    )


def test_live_table_says_when_nothing_has_run(tmp_path, monkeypatch):
    monkeypatch.setenv("DIAC_ROOT", str(tmp_path))
    text = tables.live_hypotheses()
    assert "not run" in text and "no runs yet" in text


def test_markdown_alignment():
    assert tables.markdown(("a", "b"), [(1, 2)]).splitlines()[1] == "| --- | ---: |"
