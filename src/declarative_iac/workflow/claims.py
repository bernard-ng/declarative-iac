"""`declarative-iac claims`: compare the paper's claims with the results and with the text."""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import typer

from declarative_iac.core.paths import paper_dir, relative, repository_root, results_dir
from declarative_iac.domain.claims import registry, verifier

app = typer.Typer(help="Check the paper's quantitative claims.", no_args_is_help=True)


def claims_path() -> Path:
    return repository_root() / "claims" / "claims.yaml"


def _format(value: object) -> str:
    text = repr(value) if not isinstance(value, str) else value
    return text if len(text) <= 40 else text[:37] + "..."


def report_markdown(verdicts: list[verifier.Verdict]) -> str:
    counts = Counter(v.status for v in verdicts)
    lines = [
        "# Claims report",
        "",
        "Generated by `declarative-iac claims verify` from `claims/claims.yaml` and `results/`.",
        "Do not edit by hand.",
        "",
        "| Status | Claims |",
        "|---|---:|",
        *(
            f"| {status} | {counts.get(status, 0)} |"
            for status in (verifier.PASS, verifier.FAIL, verifier.MISSING, verifier.PENDING)
        ),
        "",
        "| Claim | Evidence | Status | Claimed | Result | Detail |",
        "|---|---|---|---|---|---|",
    ]
    for v in verdicts:
        lines.append(
            f"| `{v.claim.id}` | {v.claim.evidence} | {v.status} | "
            f"{_format(v.claim.value) if v.claim.rule != 'pending' else ''} | "
            f"{_format(v.observed) if v.observed is not None else ''} | "
            f"{v.detail.replace('|', '/')} |"
        )
    return "\n".join(lines) + "\n"


@app.command("verify")
def verify(
    strict: bool = typer.Option(False, help="Treat pending claims as failures."),
    write_report: bool = typer.Option(True, help="Write results/CLAIMS_REPORT.md."),
) -> None:
    """Compare every claim with its result; exit 1 on a mismatch or a missing result."""

    claims = registry.load(claims_path())
    verdicts = [verifier.verify(claim, results_dir()) for claim in claims]
    for v in verdicts:
        if v.status != verifier.PASS:
            typer.echo(f"{v.status:8} {v.claim.id}  {v.detail}")
    counts = Counter(v.status for v in verdicts)
    typer.echo(
        f"{counts[verifier.PASS]} pass, {counts[verifier.FAIL]} fail, "
        f"{counts[verifier.MISSING]} missing, {counts[verifier.PENDING]} pending"
    )
    if write_report:
        path = results_dir() / "CLAIMS_REPORT.md"
        path.write_text(report_markdown(verdicts), encoding="utf-8")
        typer.echo(f"wrote {relative(path)}")
    bad = counts[verifier.FAIL] + counts[verifier.MISSING]
    if bad or (strict and counts[verifier.PENDING]):
        raise typer.Exit(1)


@app.command("check-paper")
def check_paper() -> None:
    """Check that each claim's text appears at its cited location in paper/sections."""

    claims = registry.load(claims_path())
    problems = [
        (claim.id, problem)
        for claim in claims
        for problem in verifier.check_paper(claim, paper_dir() / "sections")
    ]
    for claim_id, problem in problems:
        typer.echo(f"missing  {claim_id}  {problem}")
    located = sum(len(claim.locations) for claim in claims)
    typer.echo(f"{located - len(problems)} of {located} locations found")
    if problems:
        raise typer.Exit(1)


@app.command("list")
def list_claims() -> None:
    """List the claims with their evidence tier and rule."""

    for claim in registry.load(claims_path()):
        typer.echo(f"{claim.id:45} {claim.evidence:12} {claim.rule:8} {claim.statement}")
