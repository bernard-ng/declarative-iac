"""results/SUMMARY.md: one page that indexes every result and its provenance."""

from __future__ import annotations

from pathlib import Path

from declarative_iac.core.canonical import read_json
from declarative_iac.core.hashing import sha256_file
from declarative_iac.core.paths import relative, results_dir
from declarative_iac.domain.claims import registry, verifier

HEADLINES: dict[str, list[tuple[str, str]]] = {
    "S1-census": [
        ("operations", "/0.30.6/operations"),
        ("routers", "/0.30.6/routers"),
        ("used by specifications", "/0.30.6/used/operations"),
    ],
    "S2-specifications": [
        ("kinds", "/kinds"),
        ("field declarations", "/fields/declarations"),
        ("write groups", "/write_groups/total"),
    ],
    "S3-ledger": [("mapped", "/mapped"), ("unclassified", "/unclassified")],
    "S4-fixtures": [("recorded responses", "/files")],
    "S5-invariants": [("invariants", "/invariants")],
    "S6-scenarios": [
        ("scenarios", "/scenarios"),
        ("documents invalid", "/documents_invalid"),
        ("kinds exercised", "/kinds_exercised"),
    ],
    "S7-kind-references": [("lines naming a kind", "/references"), ("concerns", "/concerns")],
}


def _value(summary: object, pointer: str) -> str:
    try:
        return str(verifier.resolve_pointer(summary, pointer))
    except (KeyError, IndexError, TypeError, ValueError):
        return "—"


def build(claims_file: Path) -> str:
    root = results_dir()
    lines = [
        "<!-- Generated by `declarative-iac report`. Do not edit. -->",
        "",
        "# Results",
        "",
        "Every directory below holds the outputs of one run and its `manifest.json` (inputs, "
        "tools, host, output hashes). Claims in the paper point at these files "
        "(`claims/claims.yaml`).",
        "",
        "## Static experiments (snapshot B1)",
        "",
        "| Experiment | Headline values | Manifest sha256 |",
        "|---|---|---:|",
    ]
    for directory in sorted((root / "static").glob("*/B1")):
        manifest = directory / "manifest.json"
        summary_path = directory / "summary.json"
        if not manifest.is_file() or not summary_path.is_file():
            continue
        summary = read_json(summary_path)
        name = directory.parent.name
        values = "; ".join(f"{label} {_value(summary, p)}" for label, p in HEADLINES.get(name, []))
        lines.append(f"| `{relative(directory)}` | {values} | `{sha256_file(manifest)[:12]}` |")
    lines += ["", "## Developer evidence", ""]
    developer = sorted((root / "developer").glob("B1/*/summary.json"))
    lines += [f"- `{relative(p.parent)}`" for p in developer] or [
        "Not run in this tree (`declarative-iac developer run`, REPRODUCING.md level 1)."
    ]
    lines += ["", "## Live experiments", ""]
    live = sorted((root / "live").glob("L*/B1/summary.json"))
    for path in live:
        summary = read_json(path)
        verdicts = ", ".join(f"{k} {v['verdict']}" for k, v in summary["hypotheses"].items())
        lines.append(f"- `{relative(path.parent)}`: {summary['runs']} runs; {verdicts}")
    if not live:
        lines.append("Not run in this tree (`declarative-iac live run`, REPRODUCING.md level 2).")
    claims = registry.load(claims_file)
    verdicts = [verifier.verify(claim, root) for claim in claims]
    counts: dict[str, int] = {}
    for verdict in verdicts:
        counts[verdict.status] = counts.get(verdict.status, 0) + 1
    lines += [
        "",
        "## Claims",
        "",
        f"{len(claims)} registered claims: "
        + ", ".join(f"{n} {status}" for status, n in sorted(counts.items()))
        + ". Details: `results/CLAIMS_REPORT.md`.",
    ]
    return "\n".join(lines) + "\n"
