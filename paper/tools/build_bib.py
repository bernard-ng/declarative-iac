"""One-off: build references.bib from the DOI links cited in sections/*.md.

Records come from Crossref (DataCite for Zenodo) and are stored in tools/bib-records.json, so the
.bib can be rebuilt offline. Two records lack fields in Crossref and are completed by hand below;
one cited work has no DOI.
"""
import json, re, sys, unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
records = json.loads((HERE / "bib-records.json").read_text())

FIX = {  # Crossref records with missing fields, completed from the publisher's page
    "10.5220/0001159201830188": {"author": "Burgess, Mark",
        "title": "A Tiny Overview of Cfengine: Convergent Maintenance Agent",
        "booktitle": "Proceedings of the 1st International Workshop on Multi-Agent Robotic Systems (MARS, ICINCO 2005)"},
    "10.1109/noms.2004.1317679": {"year": "2004"},
}
NO_DOI = {"https://www.usenix.org/conference/osdi22/presentation/sun": (
    "inproceedings", {"author": "Sun, Xudong and Luo, Wenqing and Gu, Jiawei Tyler and Ganesan, Aishwarya and Alagappan, Ramnatthan and Gasch, Michael and Suresh, Lalith and Xu, Tianyin",
    "title": "Automatic Reliability Testing for Cluster Management Controllers",
    "booktitle": "Proceedings of the 16th USENIX Symposium on Operating Systems Design and Implementation (OSDI 22)",
    "publisher": "USENIX Association", "pages": "143--159", "year": "2022",
    "url": "https://www.usenix.org/conference/osdi22/presentation/sun"})}
KEEP = ("author", "title", "booktitle", "journal", "volume", "number", "pages", "publisher", "year", "doi", "url")

def fields(bib):
    kind = re.match(r"\s*@(\w+)\s*\{", bib).group(1).lower()
    out, i = {}, bib.index(",") + 1
    for m in re.finditer(r"(\w+)\s*=\s*", bib[i:]):
        pass
    # brace-aware field scan
    s = bib[bib.index(",") + 1:]
    pos = 0
    while True:
        m = re.compile(r"\s*(\w+)\s*=\s*").match(s, pos)
        if not m: break
        name, pos = m.group(1).lower(), m.end()
        if s[pos] == "{":
            depth, j = 0, pos
            while True:
                depth += {"{": 1, "}": -1}.get(s[j], 0)
                j += 1
                if depth == 0: break
            value, pos = s[pos + 1:j - 1], j
        else:
            m2 = re.compile(r"[^,}]+").match(s, pos); value, pos = m2.group(0).strip(), m2.end()
        out[name] = value
        m3 = re.compile(r"\s*,").match(s, pos)
        if not m3: break
        pos = m3.end()
    return kind, out

def ascii(s): return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()

entries = []  # (doi_or_url, kind, fields, texts)
for doi, rec in records.items():
    kind, f = fields(rec["bib"])
    if kind == "misc" and doi.startswith("10.5281/zenodo"): kind = "misc"
    f.update(FIX.get(doi, {}))
    f["doi"] = doi
    f.pop("url", None)
    entries.append((doi, kind, f, rec["texts"]))
for url, (kind, f) in NO_DOI.items():
    entries.append((url, kind, dict(f), ["Sun et al. 2022"]))

keys, mapping, seen = {}, {}, {}
for target, kind, f, texts in entries:
    sur = ascii(f["author"].split(" and ")[0].split(",")[0]).lower()
    sur = re.sub(r"[^a-z]", "", sur.split()[-1] if " " in sur else sur)
    base = f"{sur}{f['year']}"
    seen.setdefault(base, []).append((sorted(texts)[0], target))
for base, group in seen.items():
    group.sort()
    for n, (_, target) in enumerate(group):
        keys[target] = base + ("abcdefgh"[n] if len(group) > 1 else "")

lines = ["% Generated by tools/build_bib.py from Crossref and DataCite records (tools/bib-records.json).", ""]
for target, kind, f, texts in sorted(entries, key=lambda e: keys[e[0]]):
    body = []
    for name in KEEP:
        if name in f and f[name]:
            v = re.sub(r"\s+", " ", f[name]).replace("–", "--").replace("—", "---")
            while "&amp;" in v: v = v.replace("&amp;", "&")
            v = re.sub(r"(?<!\\)&", r"\\&", v)
            body.append(f"  {name} = {{{v}}},")
    lines += [f"@{kind}{{{keys[target]},"] + body + ["}", ""]
    for t in texts: mapping[t] = keys[target]
(PAPER / "references.bib").write_text("\n".join(lines))
(HERE / "cite-keys.json").write_text(json.dumps(dict(sorted(mapping.items())), indent=1) + "\n")
print(len(entries), "entries")
